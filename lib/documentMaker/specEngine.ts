// ============================================================
// Specification Document -> per-item spec text + unit
// ============================================================
//
// GeM's Specification Document (a separate PDF from the Bid Document and
// BOQ Detail Document - see app/dashboard/gem-bids/document-maker/page.tsx's
// "Upload/Replace Specification Document" button) renders its item table as
// plain text glyphs, not an image - so unlike the BOQ Detail Document (an
// actual .xlsx with real columns), its "columns" only exist as x-coordinate
// bands in the PDF's text layer. Every row is Sr No | Item Title |
// Specification | Qty | Unit, in that left-to-right order - but two real
// samples have shown two different renderings of that same layout:
//   - GEM/2026/B/8079014 (200 items): Sr No, Item Title, Qty and Unit are
//     each their own separate text item, at consistent x-bands.
//   - GEM/2026/B/8096808 (193 items, this bid's doc generated by a
//     different exporter): Sr No is glued onto the FRONT of Item Title as
//     one text item ("1 Brass Tube"), and Qty is glued onto the front of
//     Unit the same way ("50 FEET") - only Specification stands alone.
// Column x-bands also differ page-width-to-page-width between exporters,
// so fixed pixel constants can't cover both. Instead, the header row
// itself (page 1's "...SPECIFICATION..." / "...QUANTITY..." cells) is read
// to find where the Specification and Quantity columns actually start for
// THIS document, and everything left of Specification is treated as one
// "Sr No + Item Title" band, everything from Quantity onward as one
// "Qty + Unit" band - each then split by regex (leading digits vs the
// rest), which works whether the two pieces arrived as one glued string or
// as several already-separate ones (join() ends up identical either way).
import { Buffer } from "buffer";

export interface SpecItem {
  srNo: string;
  itemTitle: string;
  specification: string;
  quantity: string;
  unit: string;
}

// Column x-bands (PDF points) to fall back to when no "...SPECIFICATION..."
// / "...QUANTITY..." header cell is found on page 1 - lines up with the
// original GEM/2026/B/8079014 sample's own column positions.
const DEFAULT_BOUNDS = { specStart: 262, qtyStart: 460 };

function ensurePdfjsCanvasPolyfills(mods: { DOMMatrix: any; ImageData: any; Path2D: any; Image: any }) {
  const g = globalThis as any;
  if (!g.DOMMatrix) g.DOMMatrix = mods.DOMMatrix;
  if (!g.ImageData) g.ImageData = mods.ImageData;
  if (!g.Path2D) g.Path2D = mods.Path2D;
  if (!g.Image) g.Image = mods.Image;
}

interface TextItem {
  str: string;
  transform: number[];
}

interface ColumnBounds {
  specStart: number;
  qtyStart: number;
  // y of the header row itself (the line containing "...SPECIFICATION...")
  // - anything at or above this is the document title/header, never a row's
  // own wrapped content, which always sits below it. null when no header
  // was found (DEFAULT_BOUNDS case), in which case nothing gets clipped.
  headerY: number | null;
}

// Reads the header row's own cell positions off page 1, so the rest of the
// parse adapts to this specific document instead of a hardcoded layout.
function detectColumnBounds(items: TextItem[]): ColumnBounds {
  let specStart: number | null = null;
  let specY: number | null = null;
  let qtyStart: number | null = null;
  for (const it of items) {
    const s = it.str.trim().toUpperCase();
    if (!s) continue;
    // endsWith, not includes - the document's own title line (e.g.
    // "DOCUMENT OF SPECIFICATION FOR RAW MATERIAL BOQ") contains the word
    // too, but a genuine column header for this column always ends with
    // it ("SPECIFICATION", "DETAILED SPECIFICATION", ...).
    if (specStart === null && s.endsWith("SPECIFICATION")) {
      specStart = it.transform[4];
      specY = it.transform[5];
    }
    if (qtyStart === null && (s.endsWith("QUANTITY") || s === "QTY" || s === "QTY.")) qtyStart = it.transform[4];
  }
  if (specStart === null || qtyStart === null || qtyStart <= specStart) {
    return { ...DEFAULT_BOUNDS, headerY: null };
  }
  return { specStart, qtyStart, headerY: specY };
}

// headerClipY: the y just above which is this page's own title/header text
// (never a row's content) - only meaningful for page 1, where the first
// marker's otherwise-unbounded yTop would sweep it straight into row 1.
function parsePageRows(items: TextItem[], bounds: ColumnBounds, headerClipY: number | null): SpecItem[] {
  const { specStart, qtyStart } = bounds;

  // A row marker is a leading digit run immediately left of the
  // Specification column - whether or not it's glued onto the Item Title
  // that follows it on the same text item.
  const markers = items
    .filter((it) => it.transform[4] < specStart && /^\d+(?:\s|$)/.test(it.str.trim()))
    .map((it) => ({ y: it.transform[5], num: it.str.trim().match(/^(\d+)/)![1] }))
    .sort((a, b) => b.y - a.y);

  const col = (rowItems: TextItem[], xMin: number, xMax: number) =>
    rowItems
      .filter((it) => it.transform[4] >= xMin && it.transform[4] < xMax && it.str.trim() !== "")
      .sort((a, b) => b.transform[5] - a.transform[5] || a.transform[4] - b.transform[4])
      .map((it) => it.str.trim())
      .join(" ")
      .replace(/\s+/g, " ")
      .trim();

  const rows: SpecItem[] = [];
  for (let i = 0; i < markers.length; i++) {
    // A row's Sr No sits on its bottom-most line (a wrapped Item Title or
    // Specification cell has its Sr No digit aligned to the row's LAST
    // line, not its first) - its band runs from just below the PREVIOUS
    // marker's y down to (inclusive of) this marker's own y.
    const yTop = i === 0 ? (headerClipY ?? Infinity) : markers[i - 1].y - 1;
    const yBottom = markers[i].y - 1;
    const rowItems = items.filter((it) => it.transform[5] < yTop && it.transform[5] >= yBottom);

    const titleRaw = col(rowItems, -Infinity, specStart);
    const specification = col(rowItems, specStart, qtyStart);
    const tailRaw = col(rowItems, qtyStart, Infinity);

    const titleMatch = titleRaw.match(/^\d+\s*(.*)$/);
    const itemTitle = (titleMatch ? titleMatch[1] : titleRaw).trim();

    const tailMatch = tailRaw.match(/^(\d+(?:\.\d+)?)\s*(.*)$/);
    const quantity = tailMatch ? tailMatch[1] : tailRaw;
    const unit = tailMatch ? tailMatch[2].trim() : "";

    rows.push({ srNo: markers[i].num, itemTitle, specification, quantity, unit });
  }
  return rows;
}

/**
 * Parses a fetched Specification Document into its per-item rows, keyed by
 * srNo (matches a BOQ Detail Document's Item Number 1:1 - both come off
 * the same GeM item list in the same order). Returns [] (never throws) on
 * anything unexpected - a layout pdfjs-dist can't read, or one that just
 * doesn't look like this table - so a caller can always treat "nothing
 * usable in this file" as a plain no-op rather than a hard failure.
 */
export async function parseSpecificationPdf(buffer: Buffer | Uint8Array): Promise<SpecItem[]> {
  try {
    const canvasMods = await import("@napi-rs/canvas");
    ensurePdfjsCanvasPolyfills(canvasMods);
    const pdfjsLib = await import("pdfjs-dist/legacy/build/pdf.mjs");

    const data =
      buffer instanceof Buffer
        ? new Uint8Array(buffer.buffer, buffer.byteOffset, buffer.byteLength)
        : new Uint8Array(buffer);
    const loadingTask = pdfjsLib.getDocument({ data, useSystemFonts: true });
    try {
      const doc = await loadingTask.promise;
      const allRows: SpecItem[] = [];
      let bounds: ColumnBounds | null = null;
      for (let pageNum = 1; pageNum <= doc.numPages; pageNum++) {
        const page = await doc.getPage(pageNum);
        try {
          const content = await page.getTextContent();
          const pageItems = content.items as TextItem[];
          const isFirstPage = pageNum === 1;
          if (!bounds) bounds = detectColumnBounds(pageItems);
          allRows.push(...parsePageRows(pageItems, bounds, isFirstPage ? bounds.headerY : null));
        } finally {
          page.cleanup();
        }
      }
      return allRows;
    } finally {
      await loadingTask.destroy();
    }
  } catch (err) {
    console.error("Specification Document parse failed:", err);
    return [];
  }
}
